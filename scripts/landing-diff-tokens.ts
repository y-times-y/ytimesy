// Writes the front page preview's diff colours (src/features/landing/landing-diff-tokens.gen.ts)
// from the app's own highlighter, so the open diff paints coloured on the first render.
// Run after changing the code theme or DEMO_EDIT:
//   node --import tsx scripts/landing-diff-tokens.ts
import { writeFile } from "node:fs/promises";
import type { HighlightResult } from "@streamdown/code";
import {
	compactTokens,
	demoEditLanguage,
	demoEditSource,
} from "../src/features/landing/landing-diff-tokens";
import { codeHighlighter } from "../src/features/sessions/code-highlighter";

const result = await new Promise<HighlightResult>((resolve) => {
	const ready = codeHighlighter.highlight(
		{
			code: demoEditSource,
			language: demoEditLanguage as never,
			themes: codeHighlighter.getThemes(),
		},
		resolve,
	);
	if (ready) resolve(ready);
});
await writeFile(
	new URL(
		"../src/features/landing/landing-diff-tokens.gen.ts",
		import.meta.url,
	),
	`// Generated by scripts/landing-diff-tokens.ts. Do not edit.\nimport type { ThemedToken } from "shiki";\n\nexport const demoEditTokens: ThemedToken[][] = ${JSON.stringify(compactTokens(result.tokens))};\n`,
);
console.log("wrote landing-diff-tokens.gen.ts");
