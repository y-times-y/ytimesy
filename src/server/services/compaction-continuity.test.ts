import { type ModelMessage, simulateReadableStream, tool } from "ai";
import { MockLanguageModelV4 } from "ai/test";
import { expect, it, vi } from "vitest";
import { z } from "zod";
import { runModelAgent, runModelAgentStep } from "./model-agent-loop";

const usage = {
	inputTokens: { total: 3, noCache: 3, cacheRead: 0, cacheWrite: 0 },
	outputTokens: { total: 2, text: 2, reasoning: 0 },
};
const finish = {
	type: "finish" as const,
	usage,
	finishReason: { unified: "stop" as const, raw: "stop" },
};
const compactionUsage = {
	inputTokens: 1,
	outputTokens: 1,
	totalTokens: 2,
	inputTokenDetails: {
		noCacheTokens: 1,
		cacheReadTokens: 0,
		cacheWriteTokens: 0,
	},
	outputTokenDetails: { textTokens: 1, reasoningTokens: 0 },
};
type StreamPart =
	Awaited<
		ReturnType<typeof MockLanguageModelV4.prototype.doStream>
	>["stream"] extends ReadableStream<infer T>
		? T
		: never;
const stream = (chunks: StreamPart[]) => ({
	stream: simulateReadableStream({
		chunks,
		initialDelayInMs: null,
		chunkDelayInMs: null,
	}),
});

const requests = ["Build the settings page", "Keep tabs for indentation"];
const isUserRequest = (message: ModelMessage) =>
	message.role === "user" &&
	typeof message.content === "string" &&
	(requests.includes(message.content) || message.content === "Continue");
const history: ModelMessage[] = [
	{ role: "user", content: requests[0] },
	{ role: "assistant", content: "a".repeat(15_000) },
	{ role: "user", content: "Runtime notice: hook output" },
	{ role: "user", content: requests[1] },
	{ role: "assistant", content: "b".repeat(15_000) },
	{ role: "user", content: "Continue" },
];
/** Signed compaction replaces everything before it, as Claude's does. */
const signedCheckpoint: ModelMessage = {
	role: "assistant",
	content: [
		{
			type: "text",
			text: "Compacted earlier work",
			providerOptions: {
				anthropic: { type: "compaction", signature: "signed" },
			},
		},
	],
};
const sent = (model: MockLanguageModelV4) =>
	JSON.stringify(model.doStreamCalls[0].prompt);

it("re-adds earlier user requests after a native checkpoint that dropped them, then appends a runtime state snapshot", async () => {
	const model = new MockLanguageModelV4({
		doStream: async () => stream([finish]),
	});
	const snapshot = vi.fn(
		async (_history: ModelMessage[], _signal: AbortSignal) =>
			"## Changed files\n M src/settings.ts",
	);
	const result = await runModelAgent(
		{
			userId: "alice",
			modelId: "claude-fixture",
			instructions: "Implement",
			messages: history,
			tools: {},
			signal: new AbortController().signal,
			onEvent: async () => {},
			onStep: async () => {},
			archiveHistory: async () => "archive:fixture",
			restoreInstructions: async (messages) => [
				...messages,
				{ role: "user", content: "Restored repository instructions" },
			],
			isUserRequest,
			compactionSnapshot: snapshot,
		},
		{
			model,
			contextWindow: 16_000,
			workingContextTokens: 4_000,
			compact: async () => ({
				messages: [signedCheckpoint],
				usage: compactionUsage,
			}),
		},
	);
	expect(snapshot).toHaveBeenCalledOnce();
	expect(snapshot.mock.calls[0][0]).toEqual(history);
	expect(result[0]).toEqual(signedCheckpoint);
	const record = result[1];
	expect(record.role).toBe("user");
	expect(record.content).toContain("Earlier user messages, verbatim");
	expect(record.content).toContain(requests[0]);
	expect(record.content).toContain(requests[1]);
	expect(record.content).not.toContain("hook output");
	expect(result[2]).toEqual({ role: "user", content: "Continue" });
	expect(result[3]).toEqual({
		role: "user",
		content: "Restored repository instructions",
	});
	expect(result[4].content).toMatch(
		/^Current state snapshot, generated by the runtime[\s\S]*M src\/settings\.ts$/,
	);
	expect(sent(model)).toContain(requests[1]);
	expect(sent(model)).toContain("M src/settings.ts");
});

it("adds nothing when the native checkpoint already retains the user messages, and survives a failing snapshot", async () => {
	const model = new MockLanguageModelV4({
		doStream: async () => stream([finish]),
	});
	const result = await runModelAgent(
		{
			userId: "alice",
			modelId: "gpt-fixture",
			instructions: "Implement",
			messages: history,
			tools: {},
			signal: new AbortController().signal,
			onEvent: async () => {},
			onStep: async () => {},
			archiveHistory: async () => "archive:fixture",
			isUserRequest,
			compactionSnapshot: async () => {
				throw new Error("VM unavailable");
			},
		},
		{
			model,
			contextWindow: 16_000,
			workingContextTokens: 4_000,
			// Like OpenAI's compact endpoint: user items come back verbatim.
			compact: async ({ messages }) => ({
				messages: [
					...messages.filter((message) => message.role === "user"),
					{
						role: "assistant",
						content: [
							{
								type: "custom",
								kind: "openai.compaction",
								providerOptions: {
									openai: { itemId: "cmp", encryptedContent: "opaque" },
								},
							},
						],
					},
				],
				usage: compactionUsage,
			}),
		},
	);
	expect(JSON.stringify(result)).not.toContain("Earlier user messages");
	expect(JSON.stringify(result)).not.toContain("Current state snapshot");
	expect(JSON.stringify(result).split(requests[0]).length - 1).toBe(1);
	expect(model.doStreamCalls).toHaveLength(1);
});

it("summarizes with structured sections and keeps user requests beside the summary", async () => {
	const model = new MockLanguageModelV4({
		doGenerate: async () => ({
			content: [{ type: "text", text: "## Requirements and constraints\n- x" }],
			finishReason: { unified: "stop", raw: "stop" },
			usage,
			warnings: [],
		}),
		doStream: async () => stream([finish]),
	});
	const result = await runModelAgent(
		{
			userId: "alice",
			modelId: "fixture",
			instructions: "Implement",
			messages: [
				{ role: "user", content: requests[0] },
				{ role: "assistant", content: "a".repeat(15_000) },
				{ role: "user", content: requests[1] },
				{ role: "assistant", content: "b".repeat(15_000) },
				{ role: "user", content: "Continue" },
			],
			tools: {},
			signal: new AbortController().signal,
			onEvent: async () => {},
			onStep: async () => {},
			isUserRequest,
		},
		{ model, contextWindow: 16_000, workingContextTokens: 4_000 },
	);
	expect(JSON.stringify(model.doGenerateCalls[0].prompt)).toContain(
		"## Open TODOs",
	);
	expect(result[0].content).toContain(requests[0]);
	expect(result[1]).toMatchObject({ role: "assistant" });
	expect(result[1].content).toContain("Summary of earlier conversation");
});

it("restores user requests on an adopted background checkpoint", async () => {
	let announceCompaction = () => {};
	let announceTool = () => {};
	const compactionStarted = new Promise<void>((resolve) => {
		announceCompaction = resolve;
	});
	const toolStarted = new Promise<void>((resolve) => {
		announceTool = resolve;
	});
	const compact = vi.fn(async () => {
		announceCompaction();
		await toolStarted;
		return {
			messages: [{ role: "assistant" as const, content: "earlier checkpoint" }],
			usage: compactionUsage,
		};
	});
	const model = new MockLanguageModelV4({
		doStream: async () =>
			stream([
				{
					type: "tool-call",
					toolCallId: "read-current",
					toolName: "inspect",
					input: "{}",
				},
				{
					...finish,
					finishReason: { unified: "tool-calls", raw: "tool_calls" },
				},
			]),
	});
	const snapshot = vi.fn(async () => "state");
	const result = await runModelAgentStep(
		{
			userId: "alice",
			modelId: "gpt-6.1-sol",
			instructions: "Inspect",
			knownTools: ["inspect"],
			messages: [
				{ role: "user", content: requests[0] },
				{ role: "assistant", content: "e".repeat(5_000) },
				{ role: "user", content: requests[1] },
				{ role: "assistant", content: "e".repeat(5_500) },
				{ role: "user", content: "Continue" },
			],
			tools: {
				inspect: tool({
					inputSchema: z.object({}),
					execute: async () => {
						announceTool();
						await compactionStarted;
						return "current evidence";
					},
				}),
			},
			signal: new AbortController().signal,
			archiveHistory: async () => "archive:fixture",
			onEvent: async () => {},
			onStep: async () => {},
			isUserRequest,
			compactionSnapshot: snapshot,
		},
		{
			model,
			compact,
			contextWindow: 16000,
			workingContextTokens: 4000,
			backgroundCompaction: true,
		},
	);
	expect(compact).toHaveBeenCalledOnce();
	expect(result.messages[0]).toEqual({
		role: "assistant",
		content: "earlier checkpoint",
	});
	expect(result.messages[1].content).toContain(requests[0]);
	expect(result.messages[1].content).toContain(requests[1]);
	expect(result.messages[2]).toEqual({ role: "user", content: "Continue" });
	expect(snapshot).toHaveBeenCalledOnce();
	expect(result.messages.at(-1)?.content).toContain("state");
});
