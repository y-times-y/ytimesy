import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { expect, it, vi } from "vitest";
import { PREVIEW } from "./preview.gen";

vi.mock("@tanstack/react-router", () => ({
	Link: ({
		to,
		params,
		children,
		className,
	}: {
		to: string;
		params?: { path: string };
		children: unknown;
		className?: string;
	}) => (
		<a
			href={params ? to.replace("$path", params.path) : to}
			className={className}
		>
			{children as string}
		</a>
	),
}));

const GENERATED = resolve(import.meta.dirname, "preview.gen.ts");
const REFRESH = "Run `pnpm previews` and commit the result.";

/**
 * The front page's and the README's picture of the app is rendered from the
 * product's own components. When the sidebar, chat, composer, Overview or
 * setup card change, this fails until the picture is regenerated.
 * `pnpm previews` (scripts/update-previews.ts) sets UPDATE_PREVIEWS and
 * PREVIEW_SECTIONS_OUT (where it wants the landing sections' markup).
 */
it("the generated preview is what the product's components render today", async () => {
	const { renderPreview } = await import("./preview-demo");
	const rendered = renderPreview();
	if (process.env.UPDATE_PREVIEWS) {
		writeFileSync(
			GENERATED,
			`// Generated by \`pnpm previews\` from the product's own components (preview-demo.tsx). Do not edit.\nexport const PREVIEW = ${JSON.stringify(rendered, null, "\t")} as const;\n`,
		);
		const sections = process.env.PREVIEW_SECTIONS_OUT;
		if (sections) {
			const { renderToStaticMarkup } = await import("react-dom/server");
			const { Features, Models } = await import("../landing-page");
			const { Wordmark } = await import("#/components/brand/wordmark");
			mkdirSync(dirname(sections), { recursive: true });
			writeFileSync(
				sections,
				JSON.stringify({
					models: renderToStaticMarkup(<Models />),
					features: renderToStaticMarkup(<Features />),
					wordmark: renderToStaticMarkup(<Wordmark size={44} />),
				}),
			);
		}
		return;
	}
	expect(rendered, REFRESH).toEqual(PREVIEW);
}, 120_000);

it("shows demo data only: no person, email or secret", () => {
	const text = JSON.stringify(PREVIEW);
	expect(text).not.toMatch(/@[\w-]+\.(com|org|dev|io)\b/);
	expect(text).not.toMatch(/sk-[A-Za-z0-9]{8,}|ghp_|gho_/);
});
