import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { expect, it } from "vitest";
import { PREVIEW } from "./preview.gen";

const GENERATED = resolve(import.meta.dirname, "preview.gen.ts");
const REFRESH = "Run `pnpm previews` and commit the result.";

/**
 * The front page's and the README's picture of the app is rendered from the
 * product's own components. When the sidebar, chat, composer, Overview, or
 * the Pull requests and Issues pages change, this fails until the picture is
 * regenerated. `pnpm previews` (scripts/update-previews.ts) sets UPDATE_PREVIEWS.
 */
it("the generated preview is what the product's components render today", async () => {
	const { renderPreview } = await import("./preview-demo");
	const rendered = renderPreview();
	if (process.env.UPDATE_PREVIEWS) {
		writeFileSync(
			GENERATED,
			`// Generated by \`pnpm previews\` from the product's own components (preview-demo.tsx). Do not edit.\nexport const PREVIEW = ${JSON.stringify(rendered, null, "\t")} as const;\n`,
		);
		return;
	}
	expect(rendered, REFRESH).toEqual(PREVIEW);
}, 120_000);

it.skipIf(Boolean(process.env.UPDATE_PREVIEWS))(
	"shows the product's current UI, with demo data only",
	() => {
		const app = PREVIEW["super-agent"];
		for (const real of [
			"workspace-shell",
			"project-sidebar",
			"Super agent",
			"Needs you",
			"Working",
			"Recently finished",
			"ytimesy-3",
			"thread-mark",
			"y-overview",
			"Issues",
			"Pull requests",
		])
			expect(app, real).toContain(real);
		expect(PREVIEW["pull-requests"]).toContain("work-page");
		expect(PREVIEW.issues).toContain("New issue");
		const text = JSON.stringify(PREVIEW);
		expect(text).not.toMatch(/@[\w-]+\.(com|org|dev|io)\b/);
		expect(text).not.toMatch(/sk-[A-Za-z0-9]{8,}|ghp_|gho_/);
	},
);
